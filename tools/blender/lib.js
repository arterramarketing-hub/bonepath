/* shared by the Playwright scripts here: launch, load the real game, begin a run */
'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'../..');
const FILE=process.env.BP_INDEX||path.join(ROOT,'index.html');
const ARGS=['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader','--mute-audio'];
function pw(){try{return require('playwright');}catch(e){return require(path.join(ROOT,'tools/check/node_modules/playwright-core'));}}
function chromePath(){
  if(process.env.CHROME_PATH)return process.env.CHROME_PATH;
  try{for(const d of fs.readdirSync('/opt/pw-browsers').filter(d=>/^chromium-\d+$/.test(d)).sort().reverse()){
    const p=path.join('/opt/pw-browsers',d,'chrome-linux/chrome');if(fs.existsSync(p))return p;}}catch(e){}
  return undefined;
}
async function launch(){return pw().chromium.launch({executablePath:chromePath(),args:ARGS});}
const press=(pg,id)=>pg.evaluate(I=>{const e=document.getElementById(I);if(!e)throw new Error('no #'+I);
  e.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));},id);
/* the same way tools/check begins a run */
async function begin(browser,query,vw,vh,base){
  const pg=await browser.newPage({viewport:{width:vw||844,height:vh||390}});
  const errs=[];
  pg.on('pageerror',e=>errs.push(e.message));
  pg.on('console',m=>{if(m.type()==='error')errs.push('console: '+m.text().slice(0,200));});
  await pg.goto((base||'file://'+FILE)+'?seed=7&time=noon'+(/wx=/.test(query||'')?'':'&wx=clear')+(query||''),{waitUntil:'load'});
  await pg.waitForTimeout(4000);
  await press(pg,'modeField');
  if(await pg.evaluate(()=>window.BP?window.BP.G.mode==='title':true))await press(pg,'menuGo');
  await pg.waitForTimeout(2500);
  // ...and wait for the opening to hand the camera back: it must be standing behind the pilgrim before anything is photographed
  await pg.evaluate(()=>new Promise(r=>{const t0=performance.now(),B=window.BP;(function w(){const c=B.camera.position,P=B.player;
    if((B.G.mode==='play'&&!B.CUT.on&&Math.hypot(c.x-P.x,c.z-P.z)<9)||performance.now()-t0>12000)r();else setTimeout(w,200);})();}));
  await pg.waitForTimeout(800);
  return {pg,errs};
}
module.exports={ROOT,FILE,launch,begin,press};

/* THE REHEARSAL. The real index.html is read, and a copy is made IN MEMORY
   with the decoder and the block inlined just above makeKnightRig and one
   line added to it — exactly the change the README proposes. The file on
   disk is never written. */
function patched(){
  let h=fs.readFileSync(FILE,'utf8');
  const dec=fs.readFileSync(path.join(__dirname,'decode.js'),'utf8'),blk=fs.readFileSync(path.join(__dirname,'knight.block.json'),'utf8').trim();
  const add='/* ===== THE BLENDER KNIGHT: generated by tools/blender — re-run the script, never edit ===== */\n'+dec+'const BP_KNIGHT='+blk+';\n';
  const a='function makeKnightRig(lo){',b="armour:wiz?'wizard':sheet?'sheet':thief?'thief':og?'og':'knight'};\n  return r;";
  if(h.split(a).length!==2||h.split(b).length!==2)throw new Error('makeKnightRig has moved: update lib.js patched()');
  h=h.replace(a,()=>add+a).replace(b,()=>b.replace('  return r;',"  if(r.loadout.armour==='knight'&&!/[?&]oldknight/.test(location.search))bpDress(r,BP_KNIGHT,()=>flatMat(0xffffff));\n  return r;"));
  return {html:h,added:Buffer.byteLength(h)-fs.statSync(FILE).size};
}
/* serve the repository with index.html swapped for `html` (so icons, the manifest and sw.js resolve) */
function serve(html){
  const http=require('http');
  const types={'.html':'text/html','.js':'text/javascript','.png':'image/png','.json':'application/json','.webmanifest':'application/manifest+json'};
  const srv=http.createServer((q,s)=>{
    let p=decodeURIComponent(q.url.split('?')[0]);if(p==='/')p='/index.html';
    const f=path.join(ROOT,p);
    if(!f.startsWith(ROOT)){s.writeHead(404);s.end();return;}
    if(p==='/sw.js'){s.writeHead(200,{'content-type':'text/javascript'});s.end('/* no offline keeper in a harness */');return;}
    if(p==='/index.html'){s.writeHead(200,{'content-type':'text/html'});s.end(html);return;}
    fs.readFile(f,(e,d)=>{if(e){s.writeHead(404);s.end();}else{s.writeHead(200,{'content-type':types[path.extname(f)]||'application/octet-stream'});s.end(d);}});
  });
  return new Promise(r=>srv.listen(0,'127.0.0.1',()=>r({srv,url:'http://127.0.0.1:'+srv.address().port+'/index.html'})));
}
module.exports.patched=patched;module.exports.serve=serve;
